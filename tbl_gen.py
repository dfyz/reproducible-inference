def to_hex(x, width):
    res = x.hex()
    return res[:len('0x1.') + width] + res[-len('p??'):]


def shift_coef(orig_coef, coef_power, tbl):
    shift = -tbl.lowest_place + tbl.shifts[coef_power] + coef_power*23
    return math.ldexp(orig_coef, shift)


